"""Build .nnm files from numpy weight arrays.

Library use::

    model = build_model(layers=[(W0, b0), (W1, b1), (W2, b2)],   # float32, W[in, out]
                        width=32, encoding=ENC_BSDF_DIRS, latent=latent_hwc, ...)
    write_nnm(model, "decoder.nnm")

Command line (weights in an .npz with W0,b0,W1,b1,... and optional ``latent``
of shape (H, W, C); mip levels are generated by a box filter)::

    python -m nnm.export_numpy weights.npz out.nnm --width 32 --activation 2 \
        --beta 1.0 --eps 0.05 --transform 1 --encoding 1 --latent-levels 3
"""
from __future__ import annotations

import argparse
from typing import List, Optional, Sequence, Tuple

import numpy as np

from .format import (ACT_LEAKY_RELU, ACT_LEAKY_SMELU, ACT_RELU, BSDF_DIRS_CALLER_DIM, ENC_BSDF_DIRS, ENC_RAW,
                     OUT_NONE, NnmModel, validate_model, write_nnm)
from .reference import decode_test_inputs


def make_mip_chain(level0: np.ndarray, levels: int) -> List[np.ndarray]:
    """Box-filter pyramid of an (H,W,C) array; returns ``levels`` float16 images (level 0 first)."""
    out = [level0.astype(np.float16)]
    cur = level0.astype(np.float32)
    for _ in range(1, levels):
        h, w, c = cur.shape
        nh, nw = max(1, h >> 1), max(1, w >> 1)
        acc = np.zeros((nh, nw, c), np.float32)
        for dy in (0, 1):
            for dx in (0, 1):
                acc += cur[np.minimum(np.arange(nh) * 2 + dy, h - 1)][:, np.minimum(np.arange(nw) * 2 + dx, w - 1)]
        cur = acc / 4
        out.append(cur.astype(np.float16))
    return out


def sample_test_inputs(model: NnmModel, n: int, rng: np.random.Generator) -> np.ndarray:
    """Random caller inputs (+ u, v) laid out like the test-vector block input part."""
    if model.encoding == ENC_BSDF_DIRS:
        def hemi():
            ct = rng.uniform(0.05, 1.0, n)
            st = np.sqrt(1 - ct * ct)
            ph = rng.uniform(0, 2 * np.pi, n)
            return np.stack([st * np.cos(ph), st * np.sin(ph), ct], axis=1)
        caller = np.concatenate([hemi(), hemi()], axis=1)
    else:
        caller = rng.standard_normal((n, model.caller_dim))
    cols = [caller]
    if model.latent_channels:
        cols.append(rng.uniform(0.0, 1.0, (n, 2)))
    return np.concatenate(cols, axis=1).astype(np.float32)


def build_model(layers: Sequence[Tuple[np.ndarray, np.ndarray]], width: int, *,
                activation: int = ACT_RELU, beta: float = 0.0, eps: float = 0.0,
                output_transform: int = OUT_NONE, encoding: int = ENC_RAW,
                latent: Optional[np.ndarray] = None, latent_levels: int = 1,
                num_test_vectors: int = 16, seed: int = 0) -> NnmModel:
    """Quantise float weights to fp16 and assemble a model with generated test vectors.

    ``layers`` are (W[in, out], b[out]) in float32/float64, input-major as in the
    file. ``latent`` is (H, W, C) at level 0; extra mip levels are generated by a
    box filter. The input dim is taken from layer 0 (it includes the latent channels).
    """
    layers16 = [(np.asarray(w, np.float32).astype(np.float16), np.asarray(b, np.float32).astype(np.float16))
                for w, b in layers]
    input_dim, output_dim = layers16[0][0].shape[0], layers16[-1][0].shape[1]
    lat_levels, lat_c = [], 0
    if latent is not None:
        lat_c = latent.shape[2]
        lat_levels = make_mip_chain(np.asarray(latent, np.float32), latent_levels)
    model = NnmModel(input_dim=input_dim, output_dim=output_dim, num_hidden=len(layers16) - 1, width=width,
                     layers=layers16, activation=activation, act_beta=float(beta), act_eps=float(eps),
                     output_transform=output_transform, encoding=encoding, latent_channels=lat_c,
                     latent_levels=lat_levels)
    validate_model(model)
    if num_test_vectors:
        rng = np.random.default_rng(seed)
        tv_in = sample_test_inputs(model, num_test_vectors, rng)
        model.tv_inputs = tv_in
        model.tv_outputs = decode_test_inputs(model, tv_in)
    else:
        model.tv_inputs = np.zeros((0, model.tv_in_dim), np.float32)
        model.tv_outputs = np.zeros((0, output_dim), np.float32)
    validate_model(model)
    return model


def random_layers(rng: np.random.Generator, input_dim: int, width: int, num_hidden: int,
                  output_dim: int) -> List[Tuple[np.ndarray, np.ndarray]]:
    """Uniform fan-in-scaled random layers; used by the selftest."""
    dims = [(input_dim, width)] + [(width, width)] * (num_hidden - 1) + [(width, output_dim)]
    out = []
    for i, o in dims:
        bound = np.sqrt(6.0 / i)
        out.append((rng.uniform(-bound, bound, (i, o)).astype(np.float32),
                    rng.uniform(-0.3, 0.3, o).astype(np.float32)))
    return out


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("npz")
    ap.add_argument("out")
    ap.add_argument("--width", type=int, required=True, choices=(16, 32, 64))
    ap.add_argument("--activation", type=int, default=ACT_LEAKY_SMELU, choices=(0, 1, 2))
    ap.add_argument("--beta", type=float, default=1.0)
    ap.add_argument("--eps", type=float, default=0.05)
    ap.add_argument("--transform", type=int, default=OUT_NONE, choices=(0, 1, 2))
    ap.add_argument("--encoding", type=int, default=ENC_RAW, choices=(0, 1))
    ap.add_argument("--latent-levels", type=int, default=1)
    ap.add_argument("--tv", type=int, default=16, help="number of test vectors (0..64)")
    a = ap.parse_args(argv)
    z = np.load(a.npz)
    layers, l = [], 0
    while f"W{l}" in z:
        layers.append((z[f"W{l}"], z[f"b{l}"]))
        l += 1
    latent = z["latent"] if "latent" in z else None
    beta = a.beta if a.activation == ACT_LEAKY_SMELU else 0.0
    eps = a.eps if a.activation in (ACT_LEAKY_RELU, ACT_LEAKY_SMELU) else 0.0
    m = build_model(layers, a.width, activation=a.activation, beta=beta, eps=eps,
                    output_transform=a.transform, encoding=a.encoding, latent=latent,
                    latent_levels=a.latent_levels, num_test_vectors=a.tv)
    data = write_nnm(m, a.out)
    print(f"wrote {a.out}: {len(data)} bytes, input {m.input_dim}, hidden {m.num_hidden}x{m.width}, output {m.output_dim}")


if __name__ == "__main__":
    main()
