"""Generate intern/cycles/test/kernel_neural_mlp_test_data.h for the gtest.

    python3 -m nnm.gen_test_header [OUT_HEADER]        (run from doc/neural_rendering/tools)

Embeds a small set of .nnm files (every width, every activation and every output
transform, plus the bsdf_dirs / raw / latent variants) as uint32 word arrays so
the unit test needs no data files, and a table of reference encodings. The
output is deterministic; regenerate it whenever the format or the reference
decoder changes.
"""
from __future__ import annotations

import os
import sys

import numpy as np

from .format import write_nnm
from .reference import encode_bsdf_dirs
from .selftest import make_model, model_name

# (width, activation, output transform, structural variant, seed). The 9 (activation, transform)
# pairs are spread over the three widths so that every pair is covered once and every activation and
# every transform appears at every width. The full 27-model cross product is exercised by the
# standalone test (build_standalone_test.sh).
EMBEDDED = [
    (16, 0, 0, 0, 11), (16, 1, 1, 3, 12), (16, 2, 2, 4, 13),
    (32, 0, 1, 1, 21), (32, 1, 2, 5, 22), (32, 2, 0, 0, 23),
    (64, 0, 2, 2, 31), (64, 1, 0, 4, 32), (64, 2, 1, 1, 33),
]
NUM_TEST_VECTORS = 8

DEFAULT_OUT = os.path.join(os.path.dirname(__file__), "..", "..", "..", "..", "intern", "cycles", "test",
                           "kernel_neural_mlp_test_data.h")


def words(data: bytes):
    data = data + bytes((-len(data)) % 4)
    return np.frombuffer(data, "<u4")


def fmt_words(w) -> str:
    lines, row = [], []
    for i, x in enumerate(w):
        row.append(f"0x{int(x):08x}")
        if len(row) == 8:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    return "\n".join(lines)


def encode_cases():
    rng = np.random.default_rng(99)
    cases = [((0, 0, 1), (0, 0, 1)), ((0.6, 0, 0.8), (-0.6, 0, 0.8)), ((0.0, 0.99, 0.141067), (0.0, -0.99, 0.141067))]
    d = []
    for wi, wo in cases:
        wi, wo = np.array(wi, np.float64), np.array(wo, np.float64)
        d.append((wi / np.linalg.norm(wi), wo / np.linalg.norm(wo)))
    for _ in range(29):
        ct = rng.uniform(0.02, 1, 2)
        ph = rng.uniform(0, 2 * np.pi, 2)
        v = [np.array([np.sqrt(1 - c * c) * np.cos(p), np.sqrt(1 - c * c) * np.sin(p), c]) for c, p in zip(ct, ph)]
        d.append((v[0], v[1]))
    wi = np.array([a for a, _ in d], np.float32)
    wo = np.array([b for _, b in d], np.float32)
    return np.concatenate([wi, wo, encode_bsdf_dirs(wi, wo)], axis=1)


def main(argv=None) -> None:
    argv = sys.argv[1:] if argv is None else argv
    out_path = os.path.normpath(argv[0] if argv else DEFAULT_OUT)
    parts = [
        "/* SPDX-FileCopyrightText: 2011-2026 Blender Foundation\n"
        " *\n"
        " * SPDX-License-Identifier: Apache-2.0 */\n\n"
        "#pragma once\n\n"
        "/* Generated by doc/neural_rendering/tools/nnm/gen_test_header.py. Do not edit.\n"
        " *\n"
        " * Embedded .nnm models (little-endian bytes stored as uint32 words) with their test vectors,\n"
        " * and reference outputs of the bsdf_dirs input encoding. */\n\n"
        "#include <cstddef>\n#include <cstdint>\n\n"
        "namespace ccl::neural_test_data {\n\n"
        "struct EmbeddedModel {\n  const char *name;\n  const uint32_t *words;\n  size_t size_bytes;\n};\n\n"
    ]
    entries, total = [], 0
    for width, act, xform, variant, seed in EMBEDDED:
        m = make_model(width, act, xform, variant, seed, NUM_TEST_VECTORS)
        data = write_nnm(m)
        total += len(data)
        name = model_name(width, act, xform, variant)
        var = "k_" + name
        parts.append(f"static const uint32_t {var}[] = {{\n{fmt_words(words(data))}\n}};\n\n")
        entries.append(f'    {{"{name}", {var}, {len(data)}}},')
    parts.append("static const EmbeddedModel k_models[] = {\n" + "\n".join(entries) + "\n};\n\n")
    ec = encode_cases()
    rows = ",\n".join("    {" + ", ".join(repr(float(x)) + "f" for x in r) + "}" for r in ec)
    parts.append(f"/* wi (3), wo (3), expected encoding (12). */\nstatic const int k_num_encode_cases = {len(ec)};\n"
                 f"static const float k_encode_cases[{len(ec)}][18] = {{\n{rows}\n}};\n\n")
    parts.append("}  // namespace ccl::neural_test_data\n")
    with open(out_path, "w") as f:
        f.write("".join(parts))
    print(f"wrote {out_path}: {len(EMBEDDED)} models, {total} bytes of model data, {os.path.getsize(out_path)} bytes of source")


if __name__ == "__main__":
    main()
