/* Parity tests of the scalar reference MLP decoder (kernel/util/mlp.h) against the Python
 * reference decoder in doc/neural_rendering/tools/nnm/. The models and their expected outputs are
 * embedded in kernel_neural_mlp_test_data.h, generated by
 * `python3 -m nnm.gen_test_header` (see doc/neural_rendering/tools/nnm/README.md). */

CCL_NAMESPACE_BEGIN

namespace {

constexpr double kRelTol = 1e-4;
constexpr double kAbsTol = 1e-5;

/* The embedded arrays are uint32 words of a little-endian byte stream. */
std::vector<uint8_t> model_bytes(const neural_test_data::EmbeddedModel &model)
{
  std::vector<uint8_t> bytes(model.size_bytes);
  for (size_t i = 0; i < bytes.size(); i++) {
    bytes[i] = uint8_t(model.words[i / 4] >> (8 * (i % 4)));
  }
  return bytes;
}

}  // namespace

TEST(KernelNeuralMlp, EmbeddedModelsMatchPythonReference)
{
  bool seen_width[3] = {false, false, false};
  bool seen_activation[3] = {false, false, false};
  bool seen_transform[3] = {false, false, false};
  bool seen_bsdf_dirs = false, seen_raw = false, seen_latent = false;

  for (const neural_test_data::EmbeddedModel &model : neural_test_data::k_models) {
    SCOPED_TRACE(model.name);
    const std::vector<uint8_t> bytes = model_bytes(model);

    NnmTestModel t;
    std::string err;
    ASSERT_TRUE(nnm_parse(bytes.data(), bytes.size(), t, err)) << err;
    ASSERT_GT(t.tv_count, 0);

    double max_abs = 0.0, max_rel = 0.0;
    EXPECT_TRUE(nnm_check_test_vectors(t, kRelTol, kAbsTol, max_abs, max_rel, err)) << err;
    EXPECT_LT(max_abs, 1e-3);

    seen_width[(t.km.width == 16) ? 0 : (t.km.width == 32) ? 1 : 2] = true;
    seen_activation[t.km.activation] = true;
    seen_transform[t.km.output_transform] = true;
    seen_bsdf_dirs |= (t.km.encoding == NEURAL_ENCODING_BSDF_DIRS);
    seen_raw |= (t.km.encoding == NEURAL_ENCODING_RAW);
    seen_latent |= (t.km.latent_channels > 0);
  }

  for (int i = 0; i < 3; i++) {
    EXPECT_TRUE(seen_width[i]) << "width index " << i;
    EXPECT_TRUE(seen_activation[i]) << "activation " << i;
    EXPECT_TRUE(seen_transform[i]) << "output transform " << i;
  }
  EXPECT_TRUE(seen_bsdf_dirs);
  EXPECT_TRUE(seen_raw);
  EXPECT_TRUE(seen_latent);
}

/* Every (width, activation) pair and every (width, transform) pair must be present. */
TEST(KernelNeuralMlp, EmbeddedModelsCoverWidthsActivationsTransforms)
{
  bool act[3][3] = {}, xform[3][3] = {};
  for (const neural_test_data::EmbeddedModel &model : neural_test_data::k_models) {
    const std::vector<uint8_t> bytes = model_bytes(model);
    NnmTestModel t;
    std::string err;
    ASSERT_TRUE(nnm_parse(bytes.data(), bytes.size(), t, err)) << err;
    const int w = (t.km.width == 16) ? 0 : (t.km.width == 32) ? 1 : 2;
    act[w][t.km.activation] = true;
    xform[w][t.km.output_transform] = true;
  }
  for (int w = 0; w < 3; w++) {
    for (int i = 0; i < 3; i++) {
      EXPECT_TRUE(act[w][i]) << "width index " << w << " activation " << i;
      EXPECT_TRUE(xform[w][i]) << "width index " << w << " transform " << i;
    }
  }
}

TEST(KernelNeuralMlp, LayerOffsets)
{
  KernelNeuralModel m;
  std::memset(&m, 0, sizeof(m));
  m.input_dim = 20;
  m.output_dim = 3;
  m.num_hidden = 2;
  m.width = 32;
  /* Layer 0: 21 rows of 32. Layer 1: 33 rows of 32. Layer 2: 33 rows of pad8(3) = 8. */
  EXPECT_EQ(neural_layer_offset(m, 0), 0u);
  EXPECT_EQ(neural_layer_offset(m, 1), 21u * 32u);
  EXPECT_EQ(neural_layer_offset(m, 2), 21u * 32u + 33u * 32u);
  EXPECT_EQ(neural_layer_offset(m, 3), 21u * 32u + 33u * 32u + 33u * 8u);
  EXPECT_EQ(neural_pad8(1), 8);
  EXPECT_EQ(neural_pad8(8), 8);
  EXPECT_EQ(neural_pad8(9), 16);
  EXPECT_EQ(sizeof(KernelNeuralModel), 64u);
}

TEST(KernelNeuralMlp, EncodeBsdfDirs)
{
  using namespace neural_test_data;
  ASSERT_GT(k_num_encode_cases, 0);
  for (int n = 0; n < k_num_encode_cases; n++) {
    const float *c = k_encode_cases[n];
    float out[12];
    neural_encode_bsdf_dirs(make_float3(c[0], c[1], c[2]), make_float3(c[3], c[4], c[5]), out);
    for (int i = 0; i < 12; i++) {
      EXPECT_NEAR(out[i], c[6 + i], 1e-5 + 1e-5 * std::fabs(c[6 + i])) << "case " << n << " component " << i;
    }
    /* The difference vector is a rotation of a unit vector. */
    EXPECT_NEAR(out[9] * out[9] + out[10] * out[10] + out[11] * out[11], 1.0f, 1e-5f) << "case " << n;
  }
}

TEST(KernelNeuralMlp, Activations)
{
  const float beta = 0.8f, eps = 0.05f;
  for (int i = -300; i <= 300; i++) {
    const float x = float(i) * 0.01f;
    const double xd = x;
    EXPECT_FLOAT_EQ(neural_activation(x, NEURAL_ACTIVATION_RELU, 0.0f, 0.0f), x > 0.0f ? x : 0.0f);
    EXPECT_FLOAT_EQ(neural_activation(x, NEURAL_ACTIVATION_LEAKY_RELU, 0.0f, eps), x > 0.0f ? x : eps * x);

    const double g = (xd <= -beta) ? 0.0 : (xd >= beta) ? xd : (xd + beta) * (xd + beta) / (4.0 * beta);
    const double expected = eps * xd + (1.0 - eps) * g;
    EXPECT_NEAR(neural_activation(x, NEURAL_ACTIVATION_LEAKY_SMELU, beta, eps), expected, 2e-6) << "x = " << x;
  }
}

TEST(KernelNeuralMlp, OutputTransforms)
{
  for (int i = -400; i <= 400; i++) {
    const float x = float(i) * 0.1f;
    const double xd = x;
    EXPECT_FLOAT_EQ(neural_output_transform(x, NEURAL_OUTPUT_NONE), x);

    const double e = std::exp(std::min(std::max(xd, -20.0), 14.0));
    EXPECT_NEAR(neural_output_transform(x, NEURAL_OUTPUT_EXP), e, 1e-5 * e) << "x = " << x;

    const double sp = (xd > 20.0) ? xd : std::log1p(std::exp(xd));
    EXPECT_NEAR(neural_output_transform(x, NEURAL_OUTPUT_SOFTPLUS), sp, 2e-6 * sp + 1e-30) << "x = " << x;
  }
}

/* Corner texels are hit exactly and the centre is the average of the four neighbours. */
TEST(KernelNeuralMlp, LatentBilinear)
{
  const int w = 3, h = 2, c = 5;
  std::vector<half> junk_then_tex(7 + w * h * c);
  for (int i = 0; i < 7; i++) {
    junk_then_tex[i] = float_to_half(1000.0f);
  }
  float texel[h][w][c];
  for (int y = 0; y < h; y++) {
    for (int x = 0; x < w; x++) {
      for (int k = 0; k < c; k++) {
        texel[y][x][k] = float(1 + x + 4 * y) * 0.25f + float(k) * 0.5f;
        junk_then_tex[7 + (y * w + x) * c + k] = float_to_half(texel[y][x][k]);
      }
    }
  }

  KernelNeuralModel m;
  std::memset(&m, 0, sizeof(m));
  m.latent_channels = c;
  m.latent_width = w;
  m.latent_height = h;
  m.latent_levels = 1;
  m.latent_offset = 7;

  float z[NEURAL_MAX_LATENT_CHANNELS];
  const float us[] = {0.0f, 1.0f, 0.0f, 1.0f, 0.5f, -0.5f, 1.5f};
  const float vs[] = {0.0f, 0.0f, 1.0f, 1.0f, 1.0f, 0.0f, 1.0f};
  const int tx[] = {0, 2, 0, 2, 1, 0, 2};
  const int ty[] = {0, 0, 1, 1, 1, 0, 1};
  for (int n = 0; n < 7; n++) {
    neural_latent_sample_bilinear(junk_then_tex.data(), m, us[n], vs[n], z);
    for (int k = 0; k < c; k++) {
      EXPECT_FLOAT_EQ(z[k], half_to_float(float_to_half(texel[ty[n]][tx[n]][k]))) << "sample " << n << " channel " << k;
    }
  }

  neural_latent_sample_bilinear(junk_then_tex.data(), m, 0.25f, 0.5f, z);
  for (int k = 0; k < c; k++) {
    const float expected = 0.25f * (half_to_float(float_to_half(texel[0][0][k])) +
                                    half_to_float(float_to_half(texel[0][1][k])) +
                                    half_to_float(float_to_half(texel[1][0][k])) +
                                    half_to_float(float_to_half(texel[1][1][k])));
    EXPECT_NEAR(z[k], expected, 1e-5f) << "channel " << k;
  }
}

/* A model with an unsupported width must not read weights; it returns zeros. */
TEST(KernelNeuralMlp, DispatchRejectsUnsupportedWidth)
{
  KernelNeuralModel m;
  std::memset(&m, 0, sizeof(m));
  m.output_dim = 3;
  m.width = 48;
  float in[4] = {1.0f, 2.0f, 3.0f, 4.0f};
  float out[3] = {7.0f, 7.0f, 7.0f};
  neural_mlp_eval_dispatch(nullptr, m, in, out);
  EXPECT_EQ(out[0], 0.0f);
  EXPECT_EQ(out[1], 0.0f);
  EXPECT_EQ(out[2], 0.0f);
}

